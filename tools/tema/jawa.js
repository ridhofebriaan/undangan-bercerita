// Pembuat daftar acara ringkas: [nama, mulai, selesai|null, tempat, alamat, utama?]
function acara(tgl, kota, daftar) {
  return daftar.map(([nama, mulai, selesai, tempat, alamat, utama]) => {
    const iso = (j) => (j.includes("T") ? j : `${tgl}T${j}`) + ":00+07:00";
    const a = { nama, mulai: iso(mulai), selesai: selesai ? iso(selesai) : null, tempat, alamat, peta: `${tempat}, ${kota}` };
    if (utama) a.utama = true;
    return a;
  });
}

